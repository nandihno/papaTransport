//
//  PTVCredentials.swift
//  PapaTransport
//
//  PTV Timetable API credentials, embedded in the app binary.
//
//  The devid and API key are stored XOR-obfuscated rather than as string
//  literals: a literal is recoverable from the shipped binary with `strings`
//  in seconds. Obfuscation is friction, not security — anything in a binary
//  is extractable by a determined reader. The practical risk being managed
//  here is casual scraping, which would burn the key's rate limit.
//
//  A UserDefaults override is supported so a replacement key can be supplied
//  without shipping an App Store update if the embedded one is ever revoked.
//
//  Regenerate the arrays below with:
//      swift scripts/generate_ptv_credentials.swift <DEVID> <API_KEY>
//

import Foundation

nonisolated enum PTVCredentials {

    static let devidDefaultsKey = "ptvDevId"
    static let apiKeyDefaultsKey = "ptvApiKey"

    // ─── Generated by scripts/generate_ptv_credentials.swift ───
    // Populated 2026-07-25; verified decoding and signing against the live API.

    private static let pad: [UInt8] = [
            0x99, 0xf7, 0xd1, 0x59, 0xa9, 0x8e, 0x59, 0xe9, 0xee, 0xc9, 0x2f, 0x6a,
            0xcd, 0xaa, 0xb1, 0x9d, 0x6f, 0x79, 0x79, 0x59, 0xe2, 0x7d, 0x04, 0x02,
            0x4e, 0xe4, 0x0b, 0x47, 0xb7, 0xf2, 0x61, 0x98
        ]

    private static let obfuscatedDevid: [UInt8] = [
            0xaa, 0xc7, 0xe1, 0x6d, 0x99, 0xb9, 0x6e
        ]

    private static let obfuscatedAPIKey: [UInt8] = [
            0xaf, 0xc3, 0xe0, 0x6e, 0x9a, 0xbf, 0x6d, 0x8c, 0xc3, 0xf8, 0x4e, 0x5c,
            0xf9, 0x87, 0x85, 0xab, 0x58, 0x18, 0x54, 0x60, 0xd6, 0x4c, 0x37, 0x2f,
            0x2f, 0xd2, 0x39, 0x23, 0xd6, 0x91, 0x53, 0xfd, 0xfc, 0x95, 0xb7, 0x68
        ]

    // ───────────────────────────────────────────────────────────

    static var devid: String {
        override(for: devidDefaultsKey) ?? deobfuscate(obfuscatedDevid)
    }

    static var apiKey: String {
        override(for: apiKeyDefaultsKey) ?? deobfuscate(obfuscatedAPIKey)
    }

    static var isConfigured: Bool {
        !devid.isEmpty && !apiKey.isEmpty
    }

    private static func override(for key: String) -> String? {
        guard let value = UserDefaults.standard.string(forKey: key)?
            .trimmingCharacters(in: .whitespacesAndNewlines),
              !value.isEmpty
        else { return nil }
        return value
    }

    private static func deobfuscate(_ bytes: [UInt8]) -> String {
        guard !bytes.isEmpty, !pad.isEmpty else { return "" }
        let decoded = bytes.enumerated().map { offset, byte in
            byte ^ pad[offset % pad.count]
        }
        return String(decoding: decoded, as: UTF8.self)
    }
}
