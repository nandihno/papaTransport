#!/usr/bin/env swift
//
//  generate_ptv_credentials.swift
//
//  Generates the obfuscated byte arrays to paste into
//  PapaTransport/Services/PTV/PTVCredentials.swift.
//
//  Your plaintext devid / API key never leave this machine — this script
//  prints only the XOR'd bytes.
//
//  Usage:
//      swift scripts/generate_ptv_credentials.swift <DEVID> <API_KEY>
//
//  NOTE: this file lives outside the PapaTransport/ folder on purpose. That
//  folder is a PBXFileSystemSynchronizedRootGroup, so anything inside it is
//  compiled into the app target — a top-level script would break the build.
//

import Foundation

let args = CommandLine.arguments
guard args.count == 3 else {
    print("""
    Usage: swift scripts/generate_ptv_credentials.swift <DEVID> <API_KEY>

      DEVID    your PTV user ID   (e.g. 1234567)
      API_KEY  your PTV API key   (e.g. 9c132d31-6a30-4cac-8d8b-8a1970834799)
    """)
    exit(1)
}

let devid = args[1].trimmingCharacters(in: .whitespacesAndNewlines)
let apiKey = args[2].trimmingCharacters(in: .whitespacesAndNewlines)

var pad = [UInt8](repeating: 0, count: 32)
for index in pad.indices {
    pad[index] = UInt8.random(in: 1...255)
}

func obfuscate(_ value: String) -> [UInt8] {
    Array(value.utf8).enumerated().map { offset, byte in
        byte ^ pad[offset % pad.count]
    }
}

func format(_ bytes: [UInt8], indent: String = "        ") -> String {
    stride(from: 0, to: bytes.count, by: 12)
        .map { start in
            let line = bytes[start..<min(start + 12, bytes.count)]
                .map { String(format: "0x%02x", $0) }
                .joined(separator: ", ")
            return indent + line
        }
        .joined(separator: ",\n")
}

let obfuscatedDevid = obfuscate(devid)
let obfuscatedKey = obfuscate(apiKey)

// Round-trip check so a bad paste is caught here rather than at runtime.
func deobfuscate(_ bytes: [UInt8]) -> String {
    String(decoding: bytes.enumerated().map { $0.element ^ pad[$0.offset % pad.count] }, as: UTF8.self)
}
guard deobfuscate(obfuscatedDevid) == devid, deobfuscate(obfuscatedKey) == apiKey else {
    print("Round-trip verification failed — not emitting output.")
    exit(1)
}

print("""

// ─── Generated by scripts/generate_ptv_credentials.swift ───
// Paste the three arrays below into PTVCredentials.swift.

    private static let pad: [UInt8] = [
\(format(pad))
    ]

    private static let obfuscatedDevid: [UInt8] = [
\(format(obfuscatedDevid))
    ]

    private static let obfuscatedAPIKey: [UInt8] = [
\(format(obfuscatedKey))
    ]

// Round-trip verified: devid \(devid.count) chars, key \(apiKey.count) chars.

""")
